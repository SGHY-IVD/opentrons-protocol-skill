#!/usr/bin/env python3
"""Build/check the standalone tilt module; never import or connect to devices."""

import argparse
import ast
import hashlib
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCES = (
    "assets/python/communication/ch340_transport.py",
    "assets/python/devices/tilt_parts/device.py",
    "assets/python/devices/tilt_parts/flex.py",
)
TARGET = ROOT / "assets/python/devices/tilt.py"


def source_body(source):
    """Retain definitions/comments, dropping only packaging-only top-level nodes."""
    tree = ast.parse(source)
    lines = source.splitlines(keepends=True)
    remove = []
    for index, node in enumerate(tree.body):
        is_doc = (index == 0 and isinstance(node, ast.Expr)
                  and isinstance(node.value, ast.Constant)
                  and isinstance(node.value.value, str))
        is_import = isinstance(node, ast.ImportFrom) and (
            node.module == "__future__" or node.level > 0)
        if is_doc or is_import:
            remove.append((node.lineno - 1, node.end_lineno))
    for start, end in reversed(remove):
        del lines[start:end]
    return "".join(lines).strip()


def build():
    sections = []
    for path in SOURCES:
        source = (ROOT / path).read_text()
        digest = hashlib.sha256(source.encode()).hexdigest()
        sections.append("# === " + path + " ===\n# Source SHA-256: " + digest
                        + "\n\n" + source_body(source))
    result = (
        '"""Standalone third-party tilt module, including its USB and Flex layers.\n\n'
        'Generated by scripts/build_tilt.py from the listed source sections.\n'
        'Edit source parts and rebuild; do not maintain a second manual driver.\n'
        'PyUSB/USB backend and the actual Flex SDK remain environment dependencies.\n'
        'Import and construction do not connect to hardware.\n'
        '"""\n\nfrom __future__ import annotations\n\n'
        + "\n\n\n".join(sections) + "\n"
    )
    tree = ast.parse(result)
    if any(isinstance(n, ast.ImportFrom) and n.level for n in ast.walk(tree)):
        raise ValueError("The standalone module still has a package-relative dependency")
    names = [n.name for n in tree.body if isinstance(n, (ast.ClassDef, ast.FunctionDef))]
    if len(names) != len(set(names)):
        raise ValueError("Duplicate top-level definition in generated module")
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the committed bundle is stale")
    args = parser.parse_args()
    result = build()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != result:
            raise SystemExit("Tilt bundle is stale; run scripts/build_tilt.py")
        print("Standalone tilt bundle matches source parts")
    else:
        TARGET.write_text(result)
        print("Built assets/python/devices/tilt.py")


if __name__ == "__main__":
    main()
