#!/usr/bin/env python3
"""Build/check the standalone positive-pressure module without hardware I/O."""

import argparse
import ast
import hashlib
from pathlib import Path

from build_tilt import source_body


ROOT = Path(__file__).resolve().parents[1]
SOURCES = (
    "assets/python/communication/ch340_transport.py",
    "assets/python/devices/positive_pressure_parts/device.py",
)
TARGET = ROOT / "assets/python/devices/positive_pressure.py"


def build():
    sections = []
    for path in SOURCES:
        source = (ROOT / path).read_text()
        digest = hashlib.sha256(source.encode()).hexdigest()
        sections.append("# === " + path + " ===\n# Source SHA-256: " + digest
                        + "\n\n" + source_body(source))
    result = (
        '"""Standalone third-party positive-pressure module with its USB layer.\n\n'
        'Generated by scripts/build_positive_pressure.py from source sections.\n'
        'Edit source parts and rebuild; do not maintain a second manual driver.\n'
        'PyUSB/USB backend remain environment dependencies for real hardware.\n'
        'Import and construction do not connect to hardware.\n'
        '"""\n\nfrom __future__ import annotations\n\n'
        + "\n\n\n".join(sections) + "\n"
    )
    tree = ast.parse(result)
    if any(isinstance(n, ast.ImportFrom) and n.level for n in ast.walk(tree)):
        raise ValueError("The standalone module still has a package-relative dependency")
    names = [n.name for n in tree.body if isinstance(n, (ast.ClassDef, ast.FunctionDef))]
    if len(names) != len(set(names)):
        raise ValueError("Duplicate top-level definition in generated module")
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the bundle is stale")
    args = parser.parse_args()
    result = build()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != result:
            raise SystemExit("Pressure bundle is stale; run scripts/build_positive_pressure.py")
        print("Standalone positive-pressure bundle matches source parts")
    else:
        TARGET.write_text(result)
        print("Built assets/python/devices/positive_pressure.py")


if __name__ == "__main__":
    main()
